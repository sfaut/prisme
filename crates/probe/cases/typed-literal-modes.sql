-- Typed literals under the SQL modes: zero dates, fractions beyond 6 digits, offsets in another time zone.
SELECT @@SESSION.sql_mode AS mode_;
SET SESSION sql_mode = '';
SELECT DATE '0000-00-00' AS z, DATE '2024-05-00' AS zd, TIMESTAMP '0000-00-00 00:00:00' AS tz, {d '0000-00-00'} AS odbc_z;
SET SESSION sql_mode = 'NO_ZERO_DATE';
SELECT DATE '0000-00-00' AS z, DATE '2024-05-00' AS zd;
SET SESSION sql_mode = 'NO_ZERO_IN_DATE';
SELECT DATE '0000-00-00' AS z, DATE '2024-05-00' AS zd;
SET SESSION sql_mode = 'STRICT_TRANS_TABLES,NO_ZERO_DATE,NO_ZERO_IN_DATE';
SELECT DATE '0000-00-00' AS z;
SELECT DATE '2024-05-00' AS zd;
SELECT {d '0000-00-00'} AS odbc_z;
SET SESSION sql_mode = 'TIME_ROUND_FRACTIONAL';
SELECT TIME '07:08:09.1234567' AS t7, TIMESTAMP '2024-12-31 23:59:59.9999995' AS carry;
SET SESSION sql_mode = 'TIME_TRUNCATE_FRACTIONAL';
SELECT TIME '07:08:09.1234567' AS t7, TIMESTAMP '2024-12-31 23:59:59.9999995' AS carry;
SET SESSION sql_mode = DEFAULT;
SET SESSION time_zone = '+05:00';
SELECT TIMESTAMP '2024-05-06 01:00:00+02:00' AS off_session;
SET SESSION time_zone = DEFAULT;
