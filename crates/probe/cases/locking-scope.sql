-- Rows that a locking clause locks next to a query between parentheses:
-- each case runs in a transaction, then reads `trx_tables_locked` and
-- `trx_rows_locked` of `information_schema.INNODB_TRX`, after `DO
-- SLEEP(0.15)`, the view being cached for 0.1 s. A full scan of `lk` locks
-- 3 rows (2 rows and the supremum), of `lm` 6 (5 rows). A count of 0 can
-- also come from the streaming of the rows, the server stopping before
-- reading the locked table.
DROP TABLE IF EXISTS lk;
DROP TABLE IF EXISTS lm;
CREATE TABLE lk (id INT NOT NULL PRIMARY KEY, a INT NOT NULL) ENGINE = InnoDB;
CREATE TABLE lm (id INT NOT NULL PRIMARY KEY, a INT NOT NULL) ENGINE = InnoDB;
INSERT INTO lk VALUES (1, 10), (2, 20);
INSERT INTO lm VALUES (1, 10), (2, 20), (3, 30), (4, 40), (5, 50);
-- Each case: the rows and tables the transaction locks (lk 2 rows, lm 5 rows).
START TRANSACTION;
SELECT id FROM lk FOR UPDATE;
DO SLEEP(0.15);
SELECT 'after SELECT id FROM lk FOR UPDATE' AS c, trx_tables_locked AS tables_locked, trx_rows_locked AS rows_locked FROM information_schema.INNODB_TRX WHERE trx_mysql_thread_id = CONNECTION_ID();
ROLLBACK;
START TRANSACTION;
SELECT id FROM lm FOR UPDATE;
DO SLEEP(0.15);
SELECT 'after SELECT id FROM lm FOR UPDATE' AS c, trx_tables_locked AS tables_locked, trx_rows_locked AS rows_locked FROM information_schema.INNODB_TRX WHERE trx_mysql_thread_id = CONNECTION_ID();
ROLLBACK;
START TRANSACTION;
SELECT id FROM lk LOCK IN SHARE MODE;
DO SLEEP(0.15);
SELECT 'after SELECT id FROM lk LOCK IN SHARE MODE' AS c, trx_tables_locked AS tables_locked, trx_rows_locked AS rows_locked FROM information_schema.INNODB_TRX WHERE trx_mysql_thread_id = CONNECTION_ID();
ROLLBACK;
START TRANSACTION;
SELECT id FROM lk UNION SELECT id FROM lm FOR UPDATE;
DO SLEEP(0.15);
SELECT 'after SELECT id FROM lk UNION SELECT id FROM lm FOR UPDATE' AS c, trx_tables_locked AS tables_locked, trx_rows_locked AS rows_locked FROM information_schema.INNODB_TRX WHERE trx_mysql_thread_id = CONNECTION_ID();
ROLLBACK;
START TRANSACTION;
