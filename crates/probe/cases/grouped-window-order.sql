SELECT id, ROW_NUMBER() OVER (ORDER BY id DESC) AS r FROM gf ORDER BY id;
SELECT id, ROW_NUMBER() OVER (ORDER BY id DESC) AS r FROM gf GROUP BY id ORDER BY id DESC;
