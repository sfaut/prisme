/// Reading of `text` by `dialect`, written as in `MEASURED`.
fn reading(kind: TemporalKind, text: &str, dialect: Dialect) -> String {
    match read(kind, text, dialect) {
        Reading::Valid(value) => value.text(),
        Reading::Invalid => "!".to_string(),
        Reading::Unknown => "?".to_string(),
    }
}

#[test]
fn reads_the_strings_as_the_servers() {
    let mut wrong = Vec::new();
    for (kind, text, mysql, mariadb) in MEASURED {
        for (dialect, measured) in [(Dialect::MySql, mysql), (Dialect::MariaDb, mariadb)] {
            let read = reading(kind, text, dialect);
            let expected = if measured.starts_with('?') {
                "?"
            } else {
                measured
            };
            if read != expected {
                wrong.push(format!(
                    "{kind:?} {text:?} {dialect:?}: read {read}, measured {measured}"
                ));
            }
        }
    }
    assert!(wrong.is_empty(), "{}", wrong.join("\n"));
}

#[test]
fn reads_an_offset_in_mysql_only() {
    let offset = |text: &str, dialect| match read(Timestamp, text, dialect) {
        Reading::Valid(value) => value.offset,
        other => panic!("{text}: {other:?}"),
    };
    // Converted to the time zone of the session by MySQL 8.4.11, from
    // -14:00 to +14:00.
    for text in [
        "2024-05-06 01:00:00+02:00",
        "2024-05-06 07:08:09.123-14:00",
        "2024-05-06T07:08:09+00:00",
    ] {
        assert!(offset(text, Dialect::MySql).is_some(), "{text}");
        assert_eq!(
            read(Timestamp, text, Dialect::MariaDb),
            Reading::Invalid,
            "{text}"
        );
    }
    let value = |text| match read(Timestamp, text, Dialect::MySql) {
        Reading::Valid(value) => value.text(),
        other => panic!("{text}: {other:?}"),
    };
    assert_eq!(
        value("2024-05-06 23:59:59.9999999+02:00"),
        "2024-05-07 00:00:00.000000+02:00"
    );
}

#[test]
fn tells_the_zero_dates_of_each_sql_mode() {
    let date = |text| match read(Date, text, Dialect::MySql) {
        Reading::Valid(value) => (value.zero(), value.zero_date(), value.zero_in_date()),
        other => panic!("{text}: {other:?}"),
    };
    assert_eq!(date("0000-00-00"), (true, true, false));
    assert_eq!(date("2024-05-00"), (true, false, true));
    assert_eq!(date("0000-05-06"), (false, false, false));
}
